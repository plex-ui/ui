// @ts-check
/**
 * Builds src/tokens/tokens.generated.ts from the CSS token files, for platforms that do not read CSS (React Native).
 *
 *   node scripts/build-tokens.mjs           write the file
 *   node scripts/build-tokens.mjs --check   exit 1 when the file is stale (tests/tokens runs the same check)
 *
 * The CSS stays the one source of truth. Every custom property declared on the root, or on the root for one color
 * scheme, a pixel density, reduced motion or a phone width, lands in a layer with its raw value as written; the
 * values resolved for light and dark come from src/tokens/resolve.ts, the same evaluator the runtime uses. Properties
 * declared on other selectors (a component's own context, `[data-slot=...]`) are not tokens and are left out; the
 * file lists how many.
 *
 * Needs a Node that runs TypeScript files (22.18+, 23.6+), as it imports resolve.ts as is.
 */
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import postcss from "postcss"
import { buildLayers, resolveAll, DEFAULT_CONTEXT } from "./tokens-layers.mjs"

const here = dirname(fileURLToPath(import.meta.url))
const pkg = join(here, "..")
const out = join(pkg, "src/tokens/tokens.generated.ts")

const { layers, skipped } = buildLayers(postcss, (file) => readFileSync(join(pkg, "src/styles", file), "utf8"))
const resolved = await resolveAll(layers, DEFAULT_CONTEXT)

const header = `/* eslint-disable */
// Generated by packages/styles/scripts/build-tokens.mjs from src/styles/*.css. Do not edit:
// change the CSS, then run \`npm run generate:tokens\` at the repo root.
import type { TokenLayer, TokenValue } from "./resolve.js"
`

const body = `
/** The token layers in cascade order: later layers win where they apply. */
export const tokenLayers: readonly TokenLayer[] = ${JSON.stringify(layers, null, 2)}

/** Custom properties declared on other selectors, which are not tokens (a component's own context). */
export const skippedDeclarations = ${skipped}

/**
 * Every token resolved for a phone (${DEFAULT_CONTEXT.width}px wide, high density, motion allowed), in light and dark.
 * \`null\` marks a value that is invalid at computed value time. A length is in px, a time in ms.
 */
export const resolvedTokens: { readonly light: Readonly<Record<string, TokenValue | null>>; readonly dark: Readonly<Record<string, TokenValue | null>> } = ${JSON.stringify(resolved, null, 2)}
`

const content = header + body
if (process.argv.includes("--check")) {
  const current = readFileSync(out, "utf8")
  if (current !== content) {
    console.error("src/tokens/tokens.generated.ts is stale: run `npm run generate:tokens`")
    process.exit(1)
  }
  console.log("tokens.generated.ts is up to date")
} else {
  writeFileSync(out, content)
  console.log(`Wrote ${out}: ${layers.length} layers, ${Object.keys(resolved.light).length} tokens, ${skipped} contextual declarations skipped`)
}
