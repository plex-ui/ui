#!/usr/bin/env node
// Generates the Vue icon set (packages/vue/src/components/Icon) from the
// React one. Each React icon in packages/ui/dist is rendered to static
// markup and re-emitted as a Vue functional component that renders the same
// <svg>, with caller attributes overriding the defaults as `{...props}` does
// in React. Aliases and the index mirror packages/ui/src/components/Icon.
//
// Run after changing React icons (needs a built packages/ui):
//   npm run build:ui && npm run build:vue-icons

import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"
import { createElement } from "react"
import { renderToStaticMarkup } from "react-dom/server"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const UI_SRC = path.join(ROOT, "packages/ui/src/components/Icon")
const UI_DIST = path.join(ROOT, "packages/ui/dist/es/components/Icon/svg")
const OUT = path.join(ROOT, "packages/vue/src/components/Icon")

const TAG = /<(\/?)([a-zA-Z][\w:-]*)((?:\s+[\w:-]+="[^"]*")*)\s*(\/?)>/g
const ATTRIBUTE = /([\w:-]+)="([^"]*)"/g

const decode = (value) =>
  value
    .replaceAll("&quot;", '"')
    .replaceAll("&#x27;", "'")
    .replaceAll("&lt;", "<")
    .replaceAll("&gt;", ">")
    .replaceAll("&amp;", "&")

/** Parses the static SVG markup React produces (elements and attributes only). */
function parse(markup) {
  const root = { children: [] }
  const stack = [root]
  let consumed = 0

  for (const match of markup.matchAll(TAG)) {
    if (markup.slice(consumed, match.index).trim()) {
      throw new Error(`Unexpected text in icon markup: ${markup.slice(consumed, match.index)}`)
    }
    consumed = match.index + match[0].length

    const [, closing, tag, attributes, selfClosing] = match
    if (closing) {
      stack.pop()
      continue
    }
    const node = {
      tag,
      attributes: Object.fromEntries([...attributes.matchAll(ATTRIBUTE)].map(([, n, v]) => [n, decode(v)])),
      children: [],
    }
    stack.at(-1).children.push(node)
    if (!selfClosing) stack.push(node)
  }

  if (stack.length !== 1 || root.children.length !== 1 || root.children[0].tag !== "svg") {
    throw new Error(`Unexpected icon markup: ${markup.slice(0, 120)}`)
  }
  return root.children[0]
}

const literal = (value) => JSON.stringify(value)
const entries = (attributes) =>
  Object.entries(attributes)
    .map(([name, value]) => `${/^[A-Za-z_$][\w$]*$/.test(name) ? name : literal(name)}: ${literal(value)}`)
    .join(", ")
const objectLiteral = (attributes) => `{ ${entries(attributes)} }`

const renderChild = (node) =>
  node.children.length
    ? `h(${literal(node.tag)}, ${objectLiteral(node.attributes)}, [${node.children.map(renderChild).join(", ")}])`
    : `h(${literal(node.tag)}, ${objectLiteral(node.attributes)})`

function iconModule(name, svg) {
  return `// Generated by scripts/build-vue-icons.mjs from packages/ui/src/components/Icon/svg/${name}.tsx. Do not edit.
import { h, type FunctionalComponent, type SVGAttributes } from "vue"

const ${name}: FunctionalComponent<SVGAttributes> = (props) =>
  h("svg", { ${entries(svg.attributes)}, ...props }, [
    ${svg.children.map(renderChild).join(",\n    ")},
  ])
${name}.displayName = ${literal(name)}
// Every attribute goes through \`props\` above, overriding the defaults
${name}.inheritAttrs = false
export default ${name}
`
}

async function main() {
  const names = (await readdir(path.join(UI_SRC, "svg")))
    .filter((file) => file.endsWith(".tsx"))
    .map((file) => file.slice(0, -4))
    .sort()

  await rm(path.join(OUT, "svg"), { recursive: true, force: true })
  await mkdir(path.join(OUT, "svg"), { recursive: true })

  for (const name of names) {
    const { default: Icon } = await import(pathToFileURL(path.join(UI_DIST, `${name}.js`)).href)
    const svg = parse(renderToStaticMarkup(createElement(Icon)))
    await writeFile(path.join(OUT, "svg", `${name}.ts`), iconModule(name, svg))
  }

  // Index and aliases keep packages/ui's export lists, with .js specifiers
  const toVue = (source) =>
    source.replace(/from "\.\/(svg\/[\w]+|aliases)"/g, 'from "./$1.js"')
  const header = "// Generated by scripts/build-vue-icons.mjs from packages/ui/src/components/Icon. Do not edit.\n"
  await writeFile(path.join(OUT, "index.ts"), header + toVue(await readFile(path.join(UI_SRC, "index.tsx"), "utf8")))
  await writeFile(path.join(OUT, "aliases.ts"), header + toVue(await readFile(path.join(UI_SRC, "aliases.ts"), "utf8")))

  console.log(`[build-vue-icons] Wrote ${names.length} icons to ${path.relative(ROOT, OUT)}.`)
}

main().catch((error) => {
  console.error("[build-vue-icons]", error)
  process.exitCode = 1
})
